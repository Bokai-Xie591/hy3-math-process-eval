"""错误分类体系：每个类别给出可操作的判定标准，保证不同评审者结论一致。"""

ERROR_TYPES: dict[str, str] = {
    "E1_题意误读": "对题目条件或求解目标的理解与题面原文不符（如把'最大值'当成'最小值'）",
    "E2_概念理解错误": "对数学概念/定义的使用与标准定义不符（如混淆等差与等比数列）",
    "E3_公式定理误用": "使用了公式或定理，但其适用条件不满足，或公式本身写错",
    "E4_计算错误": "算术或代数变形结果错误，且该错误不是由前序错误传导导致",
    "E5_条件遗漏": "推导未使用题目给出的某个必要条件，或忽略隐含约束（如定义域、正整数要求）",
    "E6_跳步推导": "结论缺少充分依据：关键变形无推导、循环论证、或由特例直接推广到一般",
    "E7_幻觉编造": "引入题目中不存在的条件、数据或'定理'作为依据",
    "E8_单位量纲错误": "单位换算错误或表达式量纲不一致",
    "E9_格式不符": "最终答案未按题目要求的形式给出（如要求最简分数却给小数）",
    "E10_其他": "不属于以上任何类别的错误，需在 reason 中具体说明",
}


def taxonomy_text() -> str:
    """渲染为 prompt 中使用的分类说明文本。"""
    lines = [f"- {code}：{desc}" for code, desc in ERROR_TYPES.items()]
    return "\n".join(lines)
